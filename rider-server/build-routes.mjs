// Writes routes.generated.ts: one static import per `+api.ts` under app/api/rider and app/api/geo.
import { readdirSync, statSync, writeFileSync } from 'node:fs';
import { join, relative, dirname } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = join(here, '..');
const scopes = ['rider', 'geo'];

function walk(dir) {
  return readdirSync(dir).flatMap((name) => {
    const full = join(dir, name);
    return statSync(full).isDirectory() ? walk(full) : name.endsWith('+api.ts') ? [full] : [];
  });
}

const entries = [];
for (const scope of scopes) {
  for (const file of walk(join(root, 'app/api', scope)).sort()) {
    const rel = relative(join(root, 'app/api'), file).replace(/\+api\.ts$/, '');
    const parts = rel.split('/').filter((p) => p !== 'index');
    entries.push({ file: relative(here, file).replace(/\.ts$/, ''), pattern: '/api/' + parts.join('/') });
  }
}
entries.sort((a, b) => a.pattern.localeCompare(b.pattern));

const out = [
  '// GENERATED by rider-server/build-routes.mjs. Do not edit.',
  ...entries.map((e, i) => `import * as r${i} from '${e.file}';`),
  '',
  'export type RouteModule = Record<string, unknown>;',
  'export const ROUTES: { pattern: string; mod: RouteModule }[] = [',
  ...entries.map((e, i) => `  { pattern: ${JSON.stringify(e.pattern)}, mod: r${i} },`),
  '];',
  '',
].join('\n');
writeFileSync(join(here, 'routes.generated.ts'), out);
console.log(`rider-server: ${entries.length} routes`);
