// Bakes the launch intro's sketch canvas into src/components/intro-art.ts.
// Run after changing the shapes or their placement:  node scripts/brand/build-intro-art.mjs
//
// The canvas is laid out on a 1080×1920 design frame. Every shape becomes ONE path (all its strokes as subpaths), so
// the app animates a single dash offset per shape: dashes restart on every subpath, so all strokes of a shape draw at
// the same pen speed. Only the big monuments get a second, slightly wobbly pass (the pencil going over a line twice):
// on Android every frame of the draw-in re-renders the paths, and doubling all of them stalled the emulator.
import { writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { SHAPES } from './india-sketch-shapes.mjs';

// [shape, x, baseline y, scale, layer (0 far … 2 near), start (s), band, options]
// band 'top' hangs from the top of the screen, 'bottom' stands on the bottom edge; on tall phones the extra
// height opens up in the middle, around the logo.
const SCENE = [
  ['toran', 540, 40, 1, 2, 0.0, 'top', { tip: true }],
  ['moon', 900, 330, 0.9, 0, 0.1, 'top'],
  ['rangoli', 520, 360, 0.8, 2, 0.42, 'top'],
  ['kite', 850, 560, 1.1, 2, 0.35, 'top', { tip: true, part: 'kite' }],
  ['chai', 170, 560, 1.2, 2, 0.4, 'top'],
  ['steam', 170, 560, 1.2, 2, 0.6, 'top', { part: 'steam' }],
  // far skyline
  ['qutub', 90, 1560, 1.15, 0, 0.05, 'bottom', { tip: true }],
  ['taj', 330, 1560, 0.95, 0, 0.0, 'bottom', { tip: true, wobble: true }],
  ['indiaGate', 590, 1560, 0.9, 0, 0.12, 'bottom', { tip: true, wobble: true }],
  ['charminar', 800, 1560, 0.85, 0, 0.08, 'bottom', { tip: true, wobble: true }],
  ['hawaMahal', 1010, 1560, 0.6, 0, 0.18, 'bottom'],
  ['palm', 470, 1560, 0.8, 0, 0.3, 'bottom'],
  ['palm', 700, 1560, 0.65, 0, 0.36, 'bottom'],
  ['lamp', 190, 1560, 0.9, 0, 0.32, 'bottom'],
  ['ground', 540, 1566, 1, 0, 0.2, 'bottom'],
  // mid band
  ['gateway', 210, 1800, 0.9, 1, 0.22, 'bottom', { tip: true, wobble: true }],
  ['lotus', 560, 1790, 0.85, 1, 0.3, 'bottom', { tip: true }],
  ['temple', 870, 1800, 0.9, 1, 0.26, 'bottom', { tip: true }],
  ['palm', 400, 1800, 0.7, 1, 0.4, 'bottom'],
  ['lamp', 730, 1800, 0.8, 1, 0.42, 'bottom'],
  ['ground', 540, 1806, 1, 1, 0.3, 'bottom'],
  // near icons
  ['auto', 230, 1240, 0.9, 2, 0.45, 'bottom', { tip: true }],
  ['diya', 880, 1180, 1.2, 2, 0.5, 'bottom'],
];

const lengthOf = pts => pts.reduce((s, p, i) => (i ? s + Math.hypot(p[0] - pts[i - 1][0], p[1] - pts[i - 1][1]) : 0), 0);
const wobble = (pts, seed) => pts.map(([x, y], i) => [x + Math.sin(seed * 13.1 + i * 2.3) * 1.6, y + Math.cos(seed * 7.7 + i * 1.9) * 1.6]);
const pointAt = (p, d) => {
  for (let i = 1; i < p.length; i++) {
    const seg = Math.hypot(p[i][0] - p[i - 1][0], p[i][1] - p[i - 1][1]);
    if (d <= seg) { const f = seg ? d / seg : 0; return [p[i - 1][0] + (p[i][0] - p[i - 1][0]) * f, p[i - 1][1] + (p[i][1] - p[i - 1][1]) * f]; }
    d -= seg;
  }
  return p[p.length - 1];
};
const TIP_SAMPLES = 24;

const out = SCENE.map(([name, x, y, sc, layer, start, band, opts = {}], idx) => {
  const bake = pts => pts.map(([px, py]) => [Math.round(x + px * sc), Math.round(y + py * sc)]);
  const strokes = SHAPES[name]().filter(p => p.length > 1);
  const main = strokes.map(bake), sketch = opts.wobble ? strokes.map((p, k) => bake(wobble(p, idx * 31 + k))) : [];
  const all = [...main, ...sketch].filter(p => lengthOf(p) > 0);
  const d = all.map(p => 'M' + p.map(q => q.join(' ')).join(' ')).join('');
  const len = Math.ceil(Math.max(...all.map(lengthOf)));
  const item = { layer, band: band === 'top' ? 0 : 1, start, len, d };
  if (opts.tip) {
    const longest = main.reduce((a, b) => (lengthOf(b) > lengthOf(a) ? b : a));
    const L = lengthOf(longest);
    item.tip = Array.from({ length: TIP_SAMPLES }, (_, i) => pointAt(longest, L * i / (TIP_SAMPLES - 1)).map(Math.round)).flat();
    item.tipLen = Math.round(L);
  }
  if (opts.part) item.part = opts.part;
  if (opts.part === 'kite') item.pivot = [x, Math.round(y - 60 * sc)];
  return item;
});

const ts = `// Generated by scripts/brand/build-intro-art.mjs from scripts/brand/india-sketch-shapes.mjs — do not edit by hand.
// The launch intro's sketch canvas: Indian monuments and everyday icons on a 1080×1920 design frame.
// d: every stroke of the shape as a subpath; len: the longest stroke (the shape is fully drawn once the pen has
// travelled len); tip: ${TIP_SAMPLES} points along the longest stroke, x,y pairs, for the pencil tip; tipLen: that stroke's length.
export type Sketch = {
  layer: 0 | 1 | 2; band: 0 | 1; start: number; len: number; d: string;
  tip?: number[]; tipLen?: number; part?: 'kite' | 'steam'; pivot?: [number, number];
};

export const SKETCHES: Sketch[] = [
${out.map(o => '  ' + JSON.stringify(o) + ',').join('\n')}
];
`;
const target = fileURLToPath(new URL('../../src/components/intro-art.ts', import.meta.url));
writeFileSync(target, ts);
console.log(`wrote ${target} (${(ts.length / 1024).toFixed(1)} KB, ${out.length} shapes)`);
